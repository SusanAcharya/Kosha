export function generateScript(mode, duration, prompt) {
  const isVedic = mode === 'vedic';

  if (isVedic) {
    if (duration === 15) return vedicScript15(prompt);
    if (duration === 30) return vedicScript30(prompt);
    if (duration === 45) return vedicScript45(prompt);
  } else {
    if (duration === 15) return bioScript15(prompt);
    if (duration === 30) return bioScript30(prompt);
    if (duration === 45) return bioScript45(prompt);
  }

  // Fallback
  return isVedic ? vedicScript30(prompt) : bioScript30(prompt);
}
